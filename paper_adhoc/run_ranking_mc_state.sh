#!/usr/bin/env bash
# State-dependent ranking Monte Carlo and deterministic route robustness
# (20 Oct 2026 review of paper_ranking_uncertainty.py). Every job goes through
# paper_adhoc/gated.sh (one gated job at a time, waits for 8 free threads).
#
#   a  mc_state            state flips + beam offset, 500 draws, CORR
#   d  mc_state_flip_only  state flips + uniform offset, 500, CORR      (attribution)
#   d  mc_uniform_beam     uniform flips (0.241, 2 m) + beam offset, 500 (attribution)
#   e  route_robustness    radiant scaling, clothing +-0.1 clo, Route 3 edge shade
#   c  mc_state_corr10m / mc_state_corr40m
#   b  mc_state_n2000      (longest, last)
# After every job the tables are regenerated into $SCR/tables (never the paper):
#   python3 paper_adhoc/tabulate_ranking_mc_state.py --out "$SCR/tables"
#
# MC outputs: run_output/MMC/postprocessing/ranking_uncertainty_<name>/ (the
# published ranking_uncertainty/ is not touched). Logs: $SCR/logs/<name>.log.
# CORR: state-model calibration, paper_adhoc/calibrate_flip_correlation.py
# --flip-model state -> 2.7 m (rounded 3 m).
# Do not edit this file while it runs (bash reads scripts by offset); the
# launch below runs a frozen copy: REPO=<repo> bash <copy>.
set -uo pipefail
cd "${REPO:-$(dirname "$0")/..}"
SCR=${SCR:-/tmp/claude-1000/-home-harshin-files-fastUTEC-paper/98394eca-18c6-484b-8728-17aede7e7821/scratchpad/reruns/mc}
CORR=${CORR:-3}
OFF=${OFF:--64}
LOG="$SCR/logs"; mkdir -p "$LOG" "$SCR/tables"
G=paper_adhoc/gated.sh

tab() { nice -n 19 python3 paper_adhoc/tabulate_ranking_mc_state.py --out "$SCR/tables" \
            > "$LOG/tabulate.log" 2>&1 || echo "tabulation failed (see $LOG/tabulate.log)"; }
mc() { name=$1; shift
    echo "== $name queued ($(date '+%F %T'))"
    "$G" "$name" 8 nice -n 10 python3 paper_ranking_uncertainty.py --workers 6 \
        --departures 13 16 17 --load-offset-range "$OFF" 0 \
        --out-name "$name" --paper-dir "$SCR/$name" "$@" > "$LOG/$name.log" 2>&1
    echo "== $name rc=$? ($(date '+%F %T'))"; tab
}

mc mc_state           --flip-model state   --offset-model beam    --correlation-length-m "$CORR" --draws 500
mc mc_state_flip_only --flip-model state   --offset-model uniform --correlation-length-m "$CORR" --draws 500
mc mc_uniform_beam    --flip-model uniform --flip-rate 0.241 --offset-model beam --correlation-length-m 2 --draws 500
echo "== route_robustness queued ($(date '+%F %T'))"
"$G" route_robustness 8 nice -n 10 python3 paper_adhoc/route_robustness.py --workers 6 \
    > "$LOG/route_robustness.log" 2>&1
echo "== route_robustness rc=$? ($(date '+%F %T'))"; tab
mc mc_state_corr10m   --flip-model state --offset-model beam --correlation-length-m 10 --draws 500
mc mc_state_corr40m   --flip-model state --offset-model beam --correlation-length-m 40 --draws 500
mc mc_state_n2000     --flip-model state --offset-model beam --correlation-length-m "$CORR" --draws 2000
echo "== all done ($(date '+%F %T')); tables in $SCR/tables"
